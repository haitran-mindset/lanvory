const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('lanvory', {
  serviceSnapshot: () => ipcRenderer.invoke('lanvory:service-snapshot'),
  serviceAction: (action, input) => ipcRenderer.invoke('lanvory:service-action', action, input),
  openInbox: () => ipcRenderer.invoke('lanvory:open-inbox'),
  openNotices: () => ipcRenderer.invoke('lanvory:open-notices'),
  openTunnelUrl: (endpoint) => ipcRenderer.invoke('lanvory:open-tunnel-url', endpoint),
  discoverServices: (adapter, endpoint, pin) => ipcRenderer.invoke('lanvory:service-discover', adapter, endpoint, pin),
  revealInboxFile: (fileName) => ipcRenderer.invoke('lanvory:reveal-inbox-file', fileName),
  permissionActivity: () => ipcRenderer.invoke('lanvory:permission-activity'),
  inboxAccess: () => ipcRenderer.invoke('lanvory:inbox-access'),
  setInboxAccess: (fingerprint, allowed, duration) => ipcRenderer.invoke('lanvory:set-inbox-access', fingerprint, allowed, duration),
  fileSnapshot: () => ipcRenderer.invoke('lanvory:file-snapshot'),
  deleteTransferHistory: (id) => ipcRenderer.invoke('lanvory:delete-transfer-history', id),
  clearTransferHistory: () => ipcRenderer.invoke('lanvory:clear-transfer-history'),
  decideFile: (id, allow) => ipcRenderer.invoke('lanvory:decide-file', id, allow),
  selectFile: () => ipcRenderer.invoke('lanvory:select-file'),
  selectFolder: () => ipcRenderer.invoke('lanvory:select-folder'),
  selectDroppedFile: async (file) => {
    const filename = webUtils.getPathForFile(file);
    return filename ? ipcRenderer.invoke('lanvory:select-dropped-file', filename) : null;
  },
  selectDroppedFiles: async (files) => {
    const filenames = Array.from(files).map((file) => webUtils.getPathForFile(file)).filter(Boolean);
    return filenames.length ? ipcRenderer.invoke('lanvory:select-dropped-files', filenames) : null;
  },
  clearSelectedFile: () => ipcRenderer.invoke('lanvory:clear-selected-file'),
  removeSelectedFile: (index) => ipcRenderer.invoke('lanvory:remove-selected-file', index),
  getSelectedFiles: () => ipcRenderer.invoke('lanvory:selected-files'),
  sendFile: (adapter, endpoint, pin) => ipcRenderer.invoke('lanvory:send-file', adapter, endpoint, pin),
  cancelFileSend: () => ipcRenderer.invoke('lanvory:cancel-file-send'),
  pairingRequests: () => ipcRenderer.invoke('lanvory:pairing-requests'),
  startPairing: (adapter, endpoint, pin) => ipcRenderer.invoke('lanvory:pairing-start', adapter, endpoint, pin),
  cancelPairing: () => ipcRenderer.invoke('lanvory:pairing-cancel'),
  decidePairing: (id, approve, code) => ipcRenderer.invoke('lanvory:pairing-decision', id, approve, code),
  matchTrustedPeer: (adapter, endpoint) => ipcRenderer.invoke('lanvory:match-trusted-peer', adapter, endpoint),
  trustedPeers: () => ipcRenderer.invoke('lanvory:trusted-peers'),
  trustPeer: (adapter, endpoint, fingerprint) => ipcRenderer.invoke('lanvory:update-trust', 'trust', fingerprint, adapter, endpoint),
  revokePeer: (fingerprint) => ipcRenderer.invoke('lanvory:update-trust', 'revoke', fingerprint),
  discover: () => ipcRenderer.invoke('lanvory:discover'),
  resolveDiscovery: (adapter, name) => ipcRenderer.invoke('lanvory:discover-resolve', adapter, name),
  setInterfaceApproval: (adapter, approved) => ipcRenderer.invoke('lanvory:interface-approval', adapter, approved),
  setListener: (action, adapter, bind, pairing) => ipcRenderer.invoke('lanvory:set-listener', action, adapter, bind, pairing),
  listenerStatus: () => ipcRenderer.invoke('lanvory:listener-status'),
  copyLanAddress: (expected) => ipcRenderer.invoke('lanvory:copy-lan-address', expected),
  copyNetworkReport: () => ipcRenderer.invoke('lanvory:copy-network-report'),
  checkScope: (adapter, address) => ipcRenderer.invoke('lanvory:check-scope', adapter, address),
  interfaces: () => ipcRenderer.invoke('lanvory:interfaces'),
  loginItem: () => ipcRenderer.invoke('lanvory:login-item'),
  setLoginItem: (enabled) => ipcRenderer.invoke('lanvory:set-login-item', enabled),
  pairingAlerts: () => ipcRenderer.invoke('lanvory:pairing-alerts'),
  setPairingAlerts: (enabled) => ipcRenderer.invoke('lanvory:set-pairing-alerts', enabled),
  startMinimized: () => ipcRenderer.invoke('lanvory:start-minimized'),
  setStartMinimized: (enabled) => ipcRenderer.invoke('lanvory:set-start-minimized', enabled),
  renameDevice: (name) => ipcRenderer.invoke('lanvory:rename-device', name),
  copyFingerprint: (expected) => ipcRenderer.invoke('lanvory:copy-fingerprint', expected),
  copyPairingDetails: (expected) => ipcRenderer.invoke('lanvory:copy-pairing-details', expected),
  pingPeer: (adapter, endpoint, pin) => ipcRenderer.invoke('lanvory:ping-peer', adapter, endpoint, pin),
  clipboardState: () => ipcRenderer.invoke('lanvory:clipboard-state'),
  clipboardAccess: () => ipcRenderer.invoke('lanvory:clipboard-access'),
  setClipboardPolicy: (enabled) => ipcRenderer.invoke('lanvory:clipboard-policy', enabled),
  setClipboardAccess: (fingerprint, allowed, duration) => ipcRenderer.invoke('lanvory:set-clipboard-access', fingerprint, allowed, duration),
  clearClipboard: () => ipcRenderer.invoke('lanvory:clipboard-clear'),
  sendClipboard: (adapter, endpoint, pin, text) => ipcRenderer.invoke('lanvory:clipboard-send', adapter, endpoint, pin, text),
  copyReceivedClipboard: (text) => ipcRenderer.invoke('lanvory:clipboard-copy-latest', text),
  syncFolders: () => ipcRenderer.invoke('lanvory:sync-folders'),
  pickSyncDirectory: () => ipcRenderer.invoke('lanvory:sync-pick-dir'),
  addSyncFolder: (id, folderPath, mode) => ipcRenderer.invoke('lanvory:sync-add', id, folderPath, mode),
  removeSyncFolder: (id) => ipcRenderer.invoke('lanvory:sync-remove', id),
  scanSyncFolder: (id) => ipcRenderer.invoke('lanvory:sync-scan', id),
  setSyncFolderPaused: (id, paused) => ipcRenderer.invoke('lanvory:sync-pause', id, paused),
  setSyncAccess: (fingerprint, folderId, allowed) => ipcRenderer.invoke('lanvory:set-sync-access', fingerprint, folderId, allowed),
  syncWithPeer: (id, adapter, endpoint, pin, peerLabel) => ipcRenderer.invoke('lanvory:sync-run', id, adapter, endpoint, pin, peerLabel),
  discoverSyncFolders: (adapter, endpoint, pin) => ipcRenderer.invoke('lanvory:sync-discover', adapter, endpoint, pin),
  mountExports: () => ipcRenderer.invoke('lanvory:mount-exports'),
  exportMountFolder: (id, folderPath, readOnly) => ipcRenderer.invoke('lanvory:mount-export', id, folderPath, readOnly),
  unexportMountFolder: (id) => ipcRenderer.invoke('lanvory:mount-unexport', id),
  setMountAccess: (fingerprint, mountId, allowed) => ipcRenderer.invoke('lanvory:set-mount-access', fingerprint, mountId, allowed),
  mounts: () => ipcRenderer.invoke('lanvory:mounts'),
  discoverResources: (adapter, endpoint, pin) => ipcRenderer.invoke('lanvory:mount-discover', adapter, endpoint, pin),
  openMount: (adapter, endpoint, pin, remoteId, mountPoint) => ipcRenderer.invoke('lanvory:mount-open', adapter, endpoint, pin, remoteId, mountPoint),
  attachNativeMount: (id, mountPoint) => ipcRenderer.invoke('lanvory:mount-native', id, mountPoint),
  browseResource: (id, subPath) => ipcRenderer.invoke('lanvory:mount-browse', id, subPath),
  streamResourceChunk: (id, filePath, offset, length, etag) => ipcRenderer.invoke('lanvory:mount-stream', id, filePath, offset, length, etag),
  createResourceDir: (id, dirPath) => ipcRenderer.invoke('lanvory:mount-mkdir', id, dirPath),
  deleteResourceEntry: (id, targetPath) => ipcRenderer.invoke('lanvory:mount-delete-entry', id, targetPath),
  renameResourceEntry: (id, oldPath, newPath) => ipcRenderer.invoke('lanvory:mount-rename', id, oldPath, newPath),
  writeResourceFile: (id, filePath, content) => ipcRenderer.invoke('lanvory:mount-write', id, filePath, content),
  pollResourceEvents: (id, since) => ipcRenderer.invoke('lanvory:mount-events', id, since),
  closeMount: (id) => ipcRenderer.invoke('lanvory:mount-close', id),
  openMountInFinder: (target) => ipcRenderer.invoke('lanvory:mount-open-finder', target),
  nearbyStatus: () => ipcRenderer.invoke('lanvory:nearby-status'),
  nearbyAdvertise: (enabled) => ipcRenderer.invoke('lanvory:nearby-advertise', enabled === true),
  nearbyScan: () => ipcRenderer.invoke('lanvory:nearby-scan'),
  nearbyConnect: (serviceName) => ipcRenderer.invoke('lanvory:nearby-connect', serviceName),
  nearbyPair: (endpoint, fingerprint) => ipcRenderer.invoke('lanvory:nearby-pair', endpoint, fingerprint),
  identity: (retry) => ipcRenderer.invoke('lanvory:identity', retry === true),
  onNavigate: (callback) => {
    const listener = (_event, page) => {
      if (typeof page === 'string') callback(page);
    };
    ipcRenderer.on('lanvory:navigate', listener);
    return () => ipcRenderer.removeListener('lanvory:navigate', listener);
  },
});
